"""Generate ``review/CHANGELOG.md`` from ``Resolves: C-NNNN`` commit trailers."""

from __future__ import annotations

from .config import Config
from .gitutil import git, parse_resolves
from .store import Store


def build_changelog(cfg: Config, ref: str = "HEAD") -> str:
    store = Store(cfg)
    comments = {c["id"]: c for c in store.all()}
    out = git(cfg.root, "log", ref, "--no-merges", "--date=short", "--format=%H%x1f%ad%x1f%B%x1e")
    by_date: dict[str, list[str]] = {}
    for rec in out.split("\x1e"):
        rec = rec.strip("\n")
        if not rec.strip():
            continue
        sha, date, message = rec.split("\x1f", 2)
        ids = parse_resolves(message)
        if not ids:
            continue
        subject = message.strip().splitlines()[0]
        for cid in ids:
            c = comments.get(cid)
            where = ""
            if c:
                src = c["anchor"].get("source") or {}
                if src.get("file"):
                    where = f" `{src['file']}:{src.get('line', '?')}`"
                request = c["body"].replace("\n", " ")
                if len(request) > 100:
                    request = request[:97] + "..."
                line = f'- **{cid}**{where}: "{request}" - {subject} (`{sha.strip()[:7]}`)'
            else:
                line = f"- **{cid}**: {subject} (`{sha.strip()[:7]}`)"
            by_date.setdefault(date, []).append(line)
    parts = ["# Change log", "", "_Generated by olmcp from `Resolves:` commit trailers._", ""]
    if not by_date:
        parts.append("No changes recorded yet.")
    for date in sorted(by_date, reverse=True):
        parts += [f"## {date}", ""] + by_date[date] + [""]
    return "\n".join(parts).rstrip() + "\n"


def write_changelog(cfg: Config, ref: str = "HEAD") -> bool:
    """Write the changelog; returns True if the file content changed."""
    path = cfg.review_path / "CHANGELOG.md"
    text = build_changelog(cfg, ref)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    cfg.review_path.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True
